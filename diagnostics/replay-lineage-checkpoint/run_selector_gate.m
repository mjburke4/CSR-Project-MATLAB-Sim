function results = run_selector_gate
% Synthetic selector tests only. No simulator, startup, or model files.
folder = fileparts(mfilename('fullpath'));
originalFolder = pwd;
restoreFolder = onCleanup(@()cd(originalFolder)); %#ok<NASGU>
cd(folder);
observer = fullfile(folder,'ReplayLineageTap.m');
testFile = fullfile(folder,'test_replay_lineage_shapes.m');
assert(strcmp(which('ReplayLineageTap'),observer), ...
    'selectorGate:ObserverPath','MATLAB did not resolve the isolated observer.');
assert(strcmp(which('test_replay_lineage_shapes'),testFile), ...
    'selectorGate:TestPath','MATLAB did not resolve the isolated test file.');
fprintf('SELECTOR_GATE MATLAB=%s release=%s platform=%s\n', ...
    version,version('-release'),computer);
fprintf('Observer: %s\nTest file: %s\n',observer,testFile);
expected = strcat("test_replay_lineage_shapes/", [ ...
    "test_ackFirstBundleKeepsLaterData", ...
    "test_dataFirstBundleCountsEachMemberOnce", ...
    "test_ordinaryControlDoesNotHaveAnApp", ...
    "test_malformedSegmentsReject", ...
    "test_aggregateWithoutMembersRejects"]);
suite = matlab.unittest.TestSuite.fromFile(testFile);
assert(numel(suite)==5 && isequal(sort(string({suite.Name})),sort(expected)), ...
    'selectorGate:Discovery','Expected the exact five named tests.');
results = run(suite);
for k=1:numel(results)
    fprintf('%s Passed=%d Failed=%d Incomplete=%d\n',results(k).Name, ...
        results(k).Passed,results(k).Failed,results(k).Incomplete);
end
assert(numel(results)==5 && isequal(sort(string({results.Name})),sort(expected)) ...
    && all([results.Passed]) && ~any([results.Failed]) && ~any([results.Incomplete]), ...
    'selectorGate:Results','Expected five passes and zero incomplete results.');
assert(strcmp(which('ReplayLineageTap'),observer), ...
    'selectorGate:ObserverPath','Observer resolution changed during the tests.');
fprintf('SELECTOR_GATE PASS: 5 passed, 0 failed, 0 incomplete; no model run.\n');
end
