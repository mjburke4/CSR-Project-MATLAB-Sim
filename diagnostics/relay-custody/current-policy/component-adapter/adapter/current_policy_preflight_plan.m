function plan = current_policy_preflight_plan()
% Pure settings only: no filesystem, model, scheduler, RNG or process actions.
% This is a constructor-only preflight plan, NOT a traffic-run plan.
limits=struct('MaxNodes',64,'MaxTextUnits',128,'MaxDepth',4, ...
    'MaxEncodedBytes',512,'MaxRecords',1,'MaxRawBytes',512);
randomLimits=limits; randomLimits.MaxRecords=0; randomLimits.MaxRawBytes=0;
plan=struct('Schema','csr-current-policy-preflight-plan-v1', ...
    'CapacityBytes',16384,'ExistingChargedBytes',0,'ClusterBytes',4096, ...
    'TransportMode','nanoseconds','TransportMaxRecords',1);
plan.Random=struct('PayloadBytes',2048,'FooterBytes',0,'TemporaryBytes',0, ...
    'RecordLimits',randomLimits,'FirstDivergenceBytes',2048, ...
    'FirstDivergenceRecordLimits',limits);
plan.SyntheticDigest=struct('PayloadBytes',2048,'FooterBytes',0, ...
    'TemporaryBytes',0,'RecordLimits',limits);
plan.SyntheticJsonl=struct('PayloadBytes',512,'FooterBytes',0, ...
    'TemporaryBytes',0,'RecordLimits',limits);
plan.Claims=struct('Path',{'random_requests.digest.json','first_divergence.json', ...
    'synthetic.digest.json','synthetic.jsonl'},'PayloadBytes',{2048,2048,2048,512});
plan.ExpectedCreatedFiles={'random_requests.digest.json','synthetic.digest.json','synthetic.jsonl'};
end
