h.expect('final sink counts one application despite same-sequence and late fresh-sequence copies', ...
    numel(h.Delivered)==1 && h.Delivered{1}.Id==f.App.Id && ...
    h.Hop.stats().Duplicates==2 && h.Network.stats().DuplicateApplications==1 && ...
    h.Network.stats().PendingCustody==0,h.snapshot(), ...
    struct('unique_delivery_callbacks',1,'hop_duplicates',2,'nwk_duplicates',1,'pending_custody',0));
end
function queueFull(h)
f=h.input(7,2873,1); h.receive(f); h.receive(f);
h.expect('full queue refuses second copy without creating ownership',numel(h.Owned)==1 && ...
    h.Network.nsdpCount(f.App)==1 && h.Hop.stats().CustodyRefused==1 && ...
    h.Network.stats().QueueAdmissionRejections==1,h.snapshot(), ...
    struct('accepted_copies',1,'nsdp',1,'custody_refused',1,'queue_rejected',1));
h.Network.releaseFromHop(h.Owned{1},'fixture_capacity_release'); h.receive(f);
h.expect('refused HOP sequence remains retryable after capacity release',numel(h.Owned)==2 && ...
    h.Network.nsdpCount(f.App)==1 && h.Owned{2}.NwkCustodyId~=h.Owned{1}.NwkCustodyId, ...
    h.snapshot(),struct('accepted_copies',2,'nsdp',1,'fresh_token',true));
end
function nestedReject(h)
f=h.input(7,2873,1); h.receive(f); first=h.Owned{1};
h.ReentryFrame=f; h.ReenterOnSend=true; h.open();
h.expect('nested public callback releases old copy and accepts sibling before rejected send returns', ...
    numel(h.Owned)==2 && h.Network.nsdpCount(f.App)==1 && ...
    h.Network.stats().WaitingForHop==1 && isempty(h.Frames),h.snapshot(), ...
    struct('accepted_copies',2,'nsdp',1,'waiting',1,'outgoing',0));
h.open();
h.expect('old send return cannot reset or submit the newly accepted sibling under old token', ...
    numel(h.Frames)==1 && h.Frames{1}.App.NwkCustodyId==h.Owned{2}.NwkCustodyId && ...
    h.Frames{1}.App.NwkCustodyId~=first.NwkCustodyId && h.Network.stats().WaitingForHop==0, ...
    h.snapshot(),struct('outgoing',1,'new_token',true,'waiting',0));
end

function noAckRelease(h)
f=h.input(7,2873,1); f.AckRequired=false; f.App.AckRequired=false;
h.receive(f); second=f; second.Sequence=uint16(2); h.receive(second); h.open();
h.expect('two distinct incoming no-ACK copies both submit without HOP owners', ...
    numel(h.Frames)==2 && h.Network.nsdpCount(f.App)==2 && h.Hop.PendingDataCount==0 && ...
    ~h.Frames{1}.AckRequired && ~h.Frames{2}.AckRequired, ...
    h.snapshot(),struct('outgoing',2,'nsdp',2,'pending_hop',0,'ack_required',false));
h.Hop.notifySent(h.Frames{1}); h.Hop.notifySent(h.Frames{1});
h.Network.terminal(h.Frames{1}.App,true,'repeated_no_ack_terminal');
h.expect('direct no-ACK terminal and repeated old callbacks retain sibling', ...
    h.Network.nsdpCount(f.App)==1 && isempty(h.Releases), ...
    h.snapshot(),struct('nsdp',1,'hop_nsdp_release_callbacks',0));
h.Hop.notifySent(h.Frames{2}); h.advance(2e-6);
h.expect('second no-ACK sent indication releases final independent copy', ...
    h.Network.nsdpCount(f.App)==0 && h.Network.stats().PendingCustody==0 && ...
    numel(h.Frames)==2,h.snapshot(),struct('nsdp',0,'pending_custody',0,'outgoing',2));
end
