function summary = retryPolicyContract(directory,caseId,root,snapshot,sourceSnapshotSHA256)
%RETRYPOLICYCONTRACT Full-campus DATA queued-retry policy intervention.
% The checkpoint helper creates the stage directory and start receipt first.
% There are no observers, progress callbacks, shortened inputs or post-stop drain.
[cases,plan]=csr.scenario.tranche19Suite();
selected=find(strcmp({cases.CaseId},caseId));
if numel(selected)~=1
    error('csr:t19:Case','Expected one planned policy case.');
end
item=cases(selected);
entries=dir(directory); entries=entries(~ismember({entries.name},{'.','..'}));
if ~isfolder(directory) || ~isequal({entries.name},{'start.json'})
    error('csr:t19:IncompleteStage','The case requires a fresh stage containing only start.json.');
end
fprintf('Starting %s: %s, seed 128, complete 6000-second original campus.\n',caseId,item.Policy);
fprintf('No progress callbacks are scheduled. Started UTC: %s\n',csr.validation.Artifacts.utcNow());
completedResult=false; runClock=tic;
try
    simulation=csr.sim.NetworkSimulation(item.Config);
    result=simulation.run(); completedResult=true; elapsed=toc(runClock);
    fprintf('Case %s returned after %.1f minutes; checking and exporting evidence.\n',caseId,elapsed/60);
    if simulation.Scheduler.Now~=6000 || ~isequaln(result.Config,item.Config)
        error('csr:t19:CampusCompletion','The case must complete at the unchanged 6000-second horizon.');
    end
    if ~strcmp(result.Metadata.Backend,'portable') || ...
            ~strcmp(result.Metadata.ChannelModel,'csr-phy') || ...
            ~strcmp(result.Metadata.ModelStage,'tranche-3-autonomous-network-routing') || ...
            any(isfield(result,{'TransportTiming','LinkDiagnostics','ServiceDiagnostics'}))
        error('csr:t19:CampusMode','Expected real PHY, autonomous routing and uninstrumented continuous timing.');
    end
    [performance,applications]=csr.analysis.performanceSummary(result);
    for trace={result.ProtocolTrace,result.PhyTrace,result.ApplicationAdmissionTrace}
        times=trace{1}.TimeSeconds;
        if any(~isfinite(times) | times<0 | times>6000) || any(diff(times)<0)
            error('csr:t19:Trace','Trace times must be ordered and inside the fixed horizon.');
        end
    end
    statistics=result.Statistics;
    attempts=sum(result.ApplicationAdmissionStatistics.Attempts);
    if statistics.OmittedTraceRecords~=0 || statistics.OmittedPhyTraceRecords~=0 || ...
            attempts~=plan.expected_admission_attempts || ...
            height(result.ApplicationAdmissionTrace)~=100000 || ...
            statistics.OmittedApplicationAdmissionRecords~=attempts-100000
        error('csr:t19:Trace','Complete protocol/PHY traces and the original admission-prefix accounting are required.');
    end
    rawDirectory=fullfile(directory,'raw');
    [row,~]=csr.validation.exportResearchCase(result,rawDirectory,root,snapshot, ...
        fullfile(root,item.ScenarioFile));
    analysisDirectory=fullfile(directory,'analysis'); mkdir(analysisDirectory);
    writetable(stableText(struct2table(performance,'AsArray',true)), ...
        fullfile(analysisDirectory,'performance_summary.csv'));
    writetable(stableText(applications),fullfile(analysisDirectory,'applications.csv'));
    aggregateOptions=struct('Scenario',item.Scenario,'BucketWidthSeconds',item.BucketWidthSeconds, ...
        'SourceFile','raw/protocol_trace.csv', ...
        'SourceFileSHA256',csr.validation.Artifacts.sha256(fullfile(rawDirectory,'protocol_trace.csv')), ...
        'ScenarioSHA256',item.ScenarioSHA256,'ProfileID',item.ProfileId, ...
        'SourceSnapshotSHA256',sourceSnapshotSHA256);
    [series,provenance]=csr.analysis.benchmarkAggregates(result,aggregateOptions);
    aggregateFile=fullfile(analysisDirectory,'aggregates.csv');
    writetable(stableText(series),aggregateFile);
    provenance.output=struct('path','analysis/aggregates.csv', ...
        'sha256',csr.validation.Artifacts.sha256(aggregateFile));
    csr.validation.Artifacts.writeJson(fullfile(analysisDirectory,'aggregate_provenance.json'),provenance);
    row.CaseId=caseId; row.SourceKind=item.SourceKind; row.Policy=item.Policy;
    row.Attempts=attempts; row.AdmissionBlocked=attempts-row.Generated;
    row.OmittedApplicationAdmissionRecords=statistics.OmittedApplicationAdmissionRecords;
    writetable(stableText(struct2table(row,'AsArray',true)),fullfile(directory,'benchmark_summary.csv'));
    files=csr.validation.Artifacts.fileInventory(directory,{'start.json'});
    local=endsWith({files.path},'.mat') | endsWith({files.path},'.zip');
    manifest=struct('schema','csr-tranche19-queued-retry-case-v1','status','completed', ...
        'case_id',caseId,'policy',item.Policy,'original_case_id',item.OriginalCaseId, ...
        'case',item.PlanEntry,'scenario',item.Scenario,'scenario_sha256',item.ScenarioSHA256, ...
        'profile_id',item.ProfileId,'source_kind',item.SourceKind, ...
        'ns3_source_commit',result.Metadata.SourceCommit,'matlab_version',version, ...
        'matlab_release',version('-release'),'runtime',csr.sim.capabilities(), ...
        'result_metadata',result.Metadata,'duration_s',6000,'scheduler_stop_s',simulation.Scheduler.Now, ...
        'seed',128,'bucket_width_s',item.BucketWidthSeconds,'mode','continuous', ...
        'observer_enabled',false,'post_horizon_drain',false, ...
        'opnet_available',item.OpnetAvailable,'reference_directory',item.ReferenceDirectory, ...
        'source_files',snapshot,'source_snapshot_sha256',sourceSnapshotSHA256, ...
        'structural_checks_passed',true,'data_drained',row.DataDrained, ...
        'numerical_parity_established',false,'admission_counts_complete',true, ...
        'original_admission_trace_prefix',true, ...
        'admission_trace_omitted_records',statistics.OmittedApplicationAdmissionRecords, ...
        'files',files(~local),'local_files',files(local));
    manifestPath=fullfile(directory,'case.json');
    csr.validation.Artifacts.writeJson(manifestPath,manifest);
    summary=struct('Schema','csr-tranche19-queued-retry-summary-v1', ...
        'CaseId',caseId,'Policy',item.Policy,'OriginalBenchmarkCaseId',item.OriginalCaseId, ...
        'CompletedCaseCount',1,'DurationSeconds',6000,'SchedulerStopSeconds',simulation.Scheduler.Now, ...
        'Seed',128,'StructuralChecksPassed',true,'DefaultContinuousTiming',true, ...
        'RealPHY',true,'AutonomousRouting',true,'ObserverEnabled',false,'PostHorizonDrain',false, ...
        'RequestedPolicySameAsDefault',strcmp(item.Policy,'actual-tx'), ...
        'OriginalAdmissionTracePrefix',true,'AcceptanceEstablished',false, ...
        'NumericalParityEstablished',false,'Performance',performance, ...
        'Admissions',struct('Attempts',attempts,'Admitted',row.Generated,'Blocked',row.AdmissionBlocked, ...
            'TraceRecords',height(result.ApplicationAdmissionTrace), ...
            'OmittedTraceRecords',statistics.OmittedApplicationAdmissionRecords,'CountsComplete',true), ...
        'ProtocolTraceOmissions',statistics.OmittedTraceRecords, ...
        'PhyTraceOmissions',statistics.OmittedPhyTraceRecords,'FiniteStopPendingIsFailure',false, ...
        'ElapsedWallSeconds',elapsed, ...
        'Case',struct('CaseId',caseId,'Directory',caseId, ...
            'ManifestSHA256',csr.validation.Artifacts.sha256(manifestPath)));
    csr.validation.Artifacts.checkSnapshot(root,snapshot);
    csr.validation.Artifacts.writeJson(fullfile(directory,'summary.json'),summary);
    fprintf('%s exported: %d delivered, %d dropped, %d pending of %d admitted.\n', ...
        caseId,row.Received,row.Dropped,row.Pending,row.Generated);
catch failure
    if completedResult && ~isfile(fullfile(directory,'raw','summary.json'))
        try
            csr.analysis.exportResults(result,fullfile(directory,'partial_raw'));
        catch exportFailure
            try
                csr.validation.Artifacts.writeJson(fullfile(directory,'partial.json'), ...
                    struct('Metadata',result.Metadata,'Statistics',result.Statistics, ...
                    'ExportFailure',struct('Identifier',exportFailure.identifier,'Message',exportFailure.message)));
            catch
                % Retain the original simulation/check failure on a full disk.
            end
        end
    end
    try
        csr.validation.Artifacts.writeJson(fullfile(directory,'failure.json'), ...
            struct('Identifier',failure.identifier,'Message',failure.message,'CaseId',caseId,'Stack',failure.stack));
    catch
        % Do not replace the original failure with an output-device exception.
    end
    rethrow(failure);
end
end

function value=stableText(value)
for name=value.Properties.VariableNames
    column=value.(name{1});
    if ischar(column), value.(name{1})=string(cellstr(column));
    elseif iscellstr(column), value.(name{1})=string(column); end %#ok<ISCLSTR>
end
end
